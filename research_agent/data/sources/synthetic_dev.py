def public_task_record(task: DevTask) -> dict:
    return {
        "task_id": task.task_id,
        "question": task.question,
        "split": task.split,
        "environment_id": "synthetic-dev",
        "category": task.spec.category,
    }


def grading_record(task: DevTask) -> dict:
    spec = task.spec
    return {
        "task_id": spec.task_id,
        "answer": spec.answer,
        "aliases": list(spec.aliases),
        "gold_evidence_ids": list(spec.gold_evidence_ids),
        "support_doc_ids": list(spec.support_doc_ids),
        "facts": list(spec.facts),
        "category": spec.category,
        "scoring": spec.scoring,
        "answerable": spec.answerable,
        "notes": spec.notes,
        "search_hint": task.search_hint,
    }


def iter_public_tasks() -> list[dict]:
    return [public_task_record(task) for task in TASKS]


def iter_grading() -> list[dict]:
    return [grading_record(task) for task in TASKS]


def task_by_id() -> dict[str, DevTask]:
    return {task.task_id: task for task in TASKS}

def _bio(task_id: str, question: str, answer: str, aliases: list[str], doc_id: str, category: str, hint: str) -> DevTask:
    para = f"{doc_id}:0"
    return DevTask(
        task_id=task_id,
        question=question,
        split="dev",
        search_hint=hint,
        spec=GradingSpec(
            task_id=task_id,
            answer=answer,
            aliases=tuple(aliases),
            gold_evidence_ids=(para,),
            support_doc_ids=(doc_id,),
            facts=(answer,),
            category=category,
            scoring="exact_match",
            answerable=True,
        ),
    )


def _cs(
    task_id: str,
    question: str,
    answer: str,
    aliases: list[str],
    evidence: list[str],
    docs: list[str],
    hint: str,
    category: str = "cs-conditions",
) -> DevTask:
    return DevTask(
        task_id=task_id,
        question=question,
        split="dev",
        search_hint=hint,
        spec=GradingSpec(
            task_id=task_id,
            answer=answer,
            aliases=tuple(aliases),
            gold_evidence_ids=tuple(evidence),
            support_doc_ids=tuple(docs),
            facts=(answer,),
            category=category,
            scoring="exact_match",
            answerable=True,
        ),
    )


